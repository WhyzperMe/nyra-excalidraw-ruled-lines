import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { copyFile, mkdir } from "node:fs/promises";
import path from "node:path";

const production = process.argv[2] === "production";
const projectRoot = process.cwd();

async function copyReleaseFiles() {
  const releaseDir = path.join(projectRoot, "release");
  await mkdir(releaseDir, { recursive: true });
  for (const file of ["main.js", "styles.css", "manifest.json", "versions.json"]) {
    await copyFile(path.join(projectRoot, file), path.join(releaseDir, file));
  }
}

const releasePlugin = {
  name: "nyra-release-assets",
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length === 0) await copyReleaseFiles();
    });
  },
};

const context = await esbuild.context({
  entryPoints: {
    main: "src/main.ts",
    styles: "src/styles/index.css",
  },
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2021",
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outdir: ".",
  entryNames: "[name]",
  assetNames: "assets/[name]-[hash]",
  minify: production,
  define: {
    "process.env.NODE_ENV": JSON.stringify(production ? "production" : "development"),
  },
  plugins: production ? [releasePlugin] : [],
  banner: {
    js: "/* Generated by esbuild from the TypeScript/React source in src/. */",
    css: "/* Generated by esbuild from src/styles/index.css. */",
  },
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
  console.log("Watching TypeScript, React and CSS sources…");
}
